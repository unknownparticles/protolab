/** 编辑画布与预览的滚轮、触摸捏合、缩放基点及编辑坐标验收。 */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PROTOLAB_PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PROTOLAB_PLAYWRIGHT_MODULE).href : 'playwright');
const base = process.env.PROTOLAB_TEST_URL || 'http://127.0.0.1:4191';
const server = process.env.PROTOLAB_TEST_URL ? null : spawn(process.execPath, ['scripts/serve.mjs'], { env: { ...process.env, PORT: '4191' }, stdio: 'pipe' });
let browser;
try {
  for (let i = 0; i < 40; i++) { try { if ((await fetch(base)).ok) break; } catch {} await new Promise(resolve => setTimeout(resolve, 100)); }
  browser = await chromium.launch({ headless: true, ...(process.env.PROTOLAB_BROWSER_EXECUTABLE ? { executablePath: process.env.PROTOLAB_BROWSER_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, hasTouch: true });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.locator('[data-comp-id="lib-btn"]').click();
  await page.locator('#snapComponents').uncheck();
  await page.locator('#zoomSelect').selectOption('2');
  const canvas = page.locator('#canvasViewport'), scaler = page.locator('#canvasScaler');
  await canvas.evaluate(node => { node.scrollLeft = 80; node.scrollTop = 150; });
  const view = await canvas.boundingBox(), before = await scaler.boundingBox();
  const point = { x: view.x + view.width / 2, y: view.y + view.height / 2 };
  await page.mouse.move(point.x, point.y); await page.mouse.wheel(0, -80);
  await page.waitForFunction(() => Number(document.querySelector('#zoomSelect').value) > 2);
  const zoom = Number(await page.locator('#zoomSelect').inputValue()), after = await scaler.boundingBox();
  assert.ok(Math.abs((point.y - before.y) / 2 - (point.y - after.y) / zoom) < 1, '纵向缩放基点保持原内容坐标');
  for (let i = 0; i < 15; i++) await canvas.dispatchEvent('wheel', { deltaY: -200, clientX: point.x, clientY: point.y });
  assert.equal(await page.locator('#zoomSelect').inputValue(), '4');
  for (let i = 0; i < 20; i++) await canvas.dispatchEvent('wheel', { deltaY: 200, deltaMode: 1, clientX: point.x, clientY: point.y });
  assert.equal(await page.locator('#zoomSelect').inputValue(), '0.1');
  await page.locator('#fitBtn').click();
  assert.ok(Number(await page.locator('#zoomSelect').inputValue()) > .1);
  const cdp = await context.newCDPSession(page);
  const pinch = async (target, getZoom) => {
    const rect = await target.boundingBox(), x = rect.x + rect.width / 2, y = rect.y + Math.min(rect.height / 2, 200);
    const touches = distance => [{ x: x - distance / 2, y, id: 1 }, { x: x + distance / 2, y, id: 2 }];
    const start = await getZoom();
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: touches(100) });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: touches(160) });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.ok(Math.abs(await getZoom() - start * 1.6) < .001, '真实双指捏合改变缩放');
  };
  await page.locator('#zoomSelect').selectOption('1');
  await pinch(canvas, async () => Number(await page.locator('#zoomSelect').inputValue()));
  assert.equal(await page.locator('#propX').inputValue(), '32', '捏合不会移动组件');
  await page.locator('#zoomSelect').selectOption('1');
  await page.locator('#previewBtn').click();
  const preview = page.frameLocator('#previewFrame'), viewport = preview.locator('.preview-viewport').first();
  const frame = await (await page.locator('#previewFrame').elementHandle()).contentFrame();
  await pinch(viewport, async () => Number(await viewport.getAttribute('data-zoom')));
  await preview.getByRole('button', { name: '重置缩放', exact: true }).click();
  assert.equal(await viewport.getAttribute('data-zoom'), '1');
  const pbox = await viewport.boundingBox();
  await page.mouse.move(pbox.x + pbox.width / 2, pbox.y + 200); await page.mouse.wheel(0, -100);
  await frame.waitForFunction(() => Number(document.querySelector('.preview-viewport').dataset.zoom) > 1);
  assert.match(await preview.getByLabel('预览缩放').textContent(), /122%/);
  await viewport.dispatchEvent('wheel', { deltaY: -Math.log(2 / Number(await viewport.getAttribute('data-zoom'))) / .002, clientX: pbox.width / 2, clientY: 200 });
  assert.equal(await viewport.getAttribute('data-zoom'), '2');
  await preview.getByRole('button', { name: '编辑文字与尺寸', exact: true }).click();
  await preview.locator('[data-preview-item]').first().click({ position: { x: 10, y: 10 } });
  const handle = preview.locator('[data-resize="se"]'), hbox = await handle.boundingBox();
  const original = await preview.locator('[data-preview-item]').first().evaluate(node => ({ width: parseFloat(node.style.width), height: parseFloat(node.style.height) }));
  await page.mouse.move(hbox.x + hbox.width / 2, hbox.y + hbox.height / 2); await page.mouse.down();
  await page.mouse.move(hbox.x + hbox.width / 2 + 40, hbox.y + hbox.height / 2 + 20, { steps: 5 }); await page.mouse.up();
  await page.waitForFunction(width => Number(document.querySelector('#propW').value) === width, original.width + 20);
  assert.equal(await page.locator('#propH').inputValue(), String(original.height + 10));
  await preview.locator('[data-preview-item] button').first().dblclick();
  await preview.getByRole('textbox').fill('缩放后文字');
  await preview.getByRole('button', { name: '保存文字', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.editor-item').textContent.includes('缩放后文字'));
  await preview.getByRole('button', { name: '重置缩放', exact: true }).click();
  assert.equal(await viewport.getAttribute('data-zoom'), '1');
  const textareaScale = await viewport.getAttribute('data-zoom');
  await preview.locator('[data-preview-item] button').first().dblclick();
  await preview.getByRole('textbox').dispatchEvent('wheel', { deltaY: -100 });
  assert.equal(await viewport.getAttribute('data-zoom'), textareaScale);
  await preview.getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('[data-close="previewDialog"]').click(); await page.locator('#previewBtn').click();
  assert.equal(await viewport.getAttribute('data-zoom'), '1', '重新打开预览恢复默认缩放');
  assert.deepEqual(errors, []);
  console.log('通过：两处滚轮与真实双指捏合、缩放边界、基点、适应窗口、重置、缩放后尺寸及文字编辑，无脚本错误');
} finally { await browser?.close(); server?.kill(); }
